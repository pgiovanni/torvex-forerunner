    def _system_prompt(self, character: str, with_commands: bool = False,
                       with_energy: bool = False) -> str:
        """Persona + hard rules, plus the command index only when asked for.

        The index lives in docs/commands.json and is attached on demand —
        pre-gated on the question, or fetched via the NEED_COMMANDS retry in
        _generate — so ordinary chat never pays for the ~4k-token list.
        Volatile parts (channel glance, the question) live in user_content,
        and the rules sit in `system`, where a member typing "ignore your
        command list" lands underneath them rather than over them."""
        parts = [PERSONAS.get(character, PERSONAS["peepo"]), BASE_RULES]
        if not self._commands.available:
            parts.append(COMMAND_RULES_MISSING)
        elif with_commands:
            parts += [self._commands.block(), COMMAND_RULES]
        else:
            parts.append(COMMAND_RULES_ONDEMAND)
        parts.append(self._energy_info_block() if with_energy
                     else ENERGY_RULES_ONDEMAND)
        return "\n\n".join(parts)

    # ── accounting helpers ────────────────────────────────────────────────────

    @staticmethod
    def _today() -> str:
        return time.strftime("%Y-%m-%d", time.gmtime())

    def _user_spent_today(self, user_id: str) -> int:
        with self._conn() as c:
            row = c.execute(
                "SELECT COALESCE(SUM(micro),0) FROM ai_usage WHERE user_id=? AND day=?",
                (user_id, self._today()),
            ).fetchone()
        return row[0]

    def _month_spent(self, guild_id=None) -> int:
        """This month's spend — global, or one guild's when guild_id is given."""
        with self._conn() as c:
            if guild_id is None:
                row = c.execute(
                    "SELECT COALESCE(SUM(micro),0) FROM ai_usage WHERE day LIKE ?",
                    (month_key(self._today()) + "-%",),
                ).fetchone()
            else:
                row = c.execute(
                    "SELECT COALESCE(SUM(micro),0) FROM ai_usage "
                    "WHERE day LIKE ? AND guild_id=?",
                    (month_key(self._today()) + "-%", str(guild_id)),
                ).fetchone()
        return row[0]

    def _credit_balance(self, guild_id) -> int:
        """Prepaid credit remaining (µ$): lifetime grants minus lifetime spend."""
        with self._conn() as c:
            granted = c.execute(
                "SELECT COALESCE(SUM(micro),0) FROM ai_credit WHERE guild_id=?",
                (str(guild_id),)).fetchone()[0]
            spent = c.execute(
                "SELECT COALESCE(SUM(micro),0) FROM ai_usage WHERE guild_id=?",
                (str(guild_id),)).fetchone()[0]
        return granted - spent

    def _record(self, guild_id, user_id, model, tokens_in, tokens_out, micro, bucks=0):
        with self._conn() as c:
            c.execute(
                "INSERT INTO ai_usage(ts, day, guild_id, user_id, model, tokens_in, tokens_out, micro, bucks) "
                "VALUES (?,?,?,?,?,?,?,?,?)",
                (int(time.time()), self._today(), str(guild_id), str(user_id),
                 model, tokens_in, tokens_out, micro, bucks),
            )

    # ── peepo bucks (Economy cog's Postgres pool, /redeem debit pattern) ─────

    async def _debit_bucks(self, user: discord.abc.User, amount: int):
        """Atomically charge bucks. Returns new balance, or None if broke/unavailable."""
        eco = self.bot.get_cog("Economy")
        if eco is None or getattr(eco, "pool", None) is None:
            return None
        await eco.get_or_create(user)
        return await eco.pool.fetchrow(
            "UPDATE discord_users SET peepo_bucks = peepo_bucks - $1 "
            "WHERE discord_id = $2 AND peepo_bucks >= $1 RETURNING peepo_bucks",
            amount, str(user.id),
        )

    async def _refund_bucks(self, user: discord.abc.User, amount: int):
        eco = self.bot.get_cog("Economy")
        if eco is None or getattr(eco, "pool", None) is None:
            return
        await eco.pool.execute(
            "UPDATE discord_users SET peepo_bucks = peepo_bucks + $1 WHERE discord_id = $2",
            amount, str(user.id),
        )

    # ── context ───────────────────────────────────────────────────────────────

    async def _channel_context(self, channel, guild, skip_message_id=None) -> str:
        """Recent messages from the invoking channel, but ONLY if @everyone can
        see it — private/staff channels never feed the prompt."""
        try:
            if not channel.permissions_for(guild.default_role).view_channel:
                return ""
            lines = []
            async for m in channel.history(limit=CONTEXT_MESSAGES):
                if m.author.bot or not m.content or m.id == skip_message_id:
                    continue
                if str(m.author.id) in self._optout:
                    continue  # user opted out of ever appearing in AI context
                snippet = m.content[:CONTEXT_SNIPPET]
                lines.append(f"{m.author.display_name}: {snippet}")
            lines.reverse()
            return "\n".join(lines)
        except discord.HTTPException:
            return ""

    # ── shared request pipeline (used by /ask and ping-to-chat) ──────────────

    async def _precheck(self, user, tier, guild_id=None):
        """Budget + energy gate. Returns (bucks_charged, None) on go,
        (0, error_message) on stop. Debits bucks up front when past free energy."""
        if self._month_spent() >= budget_micro(MONTHLY_BUDGET_USD):
            return 0, "🧯 The AI hit this month's server-wide budget. Back on the 1st!"
        # Paid guilds spend against their own PREPAID credit — what they paid
        # for is what they can use, and it can't drain anyone else's.
        if guild_id is not None and guild_id != HOME_GUILD_ID:
            if self._credit_balance(guild_id) <= 0:
                return 0, ("🧯 This server's prepaid AI credit is used up — "
                           "top up at <https://torvex.app/Packages> to keep "
                           "the AI going.")
        if remaining_energy(self._user_spent_today(str(user.id))) <= 0:
            price = BUCKS_PRICE[tier]
            debited = await self._debit_bucks(user, price)
            if debited is None:
                return 0, (
                    f"⚡ You're out of AI energy for today (resets at midnight UTC).\n"
                    f"Extra uses cost **{BUCKS_PRICE['smart']} 💰** (or **{BUCKS_PRICE['quick']} 💰** "
                    f"with `quick: True`) — you don't have enough bucks right now.")
            return price, None
        return 0, None

    async def _generate(self, guild, channel, user, question, tier, character,
                        bucks_charged, skip_message_id=None, replied_to=None):
        """Call the model, meter the cost. Returns (text, footer, None) on
        success, (None, None, error_message) on failure (bucks refunded)."""
        model = MODEL_QUICK if tier == "quick" else MODEL_SMART
        user_id = str(user.id)

        context = await self._channel_context(channel, guild, skip_message_id)
        user_content = (
            (f"Recent messages in #{channel.name}:\n{context}\n\n" if context else "")
            + (f"Your earlier message they are replying to:\n{replied_to[:1500]}\n\n"
               if replied_to else "")
            + f"{user.display_name} asks: {question}"
        )
        # The command index and the energy reference are both on-demand
        # (Paul, 8/19): attached up front only when the question plainly
        # needs them; otherwise the model requests one by replying with a
        # NEED_* sentinel and the call runs once more with that block.
        qlow = (question or "").lower()
        attach_cmds = self._commands.available and (
            "command" in qlow or self._commands.mentioned_in(question))
        attach_energy = any(w in qlow for w in (
            "energy", "ai-usage", "ai usage", "cooldown", "bucks", "cost", "pay"))
        system = self._system_prompt(character, with_commands=attach_cmds,
                                     with_energy=attach_energy)

        try:
            result = await self.provider.chat(
                model=model, system=system,
                user_content=user_content, max_tokens=MAX_OUT_TOKENS)
        except Exception as e:
            log.error("AI call failed: %s", e)
            if bucks_charged:
                await self._refund_bucks(user, bucks_charged)
            return None, None, (
                "😵 The AI didn't answer — try again in a minute."
                + (f" Your {bucks_charged} 💰 was refunded." if bucks_charged else ""))

        micro = cost_micro(model, result.tokens_in, result.tokens_out)
        self._record(guild.id, user_id, model,
                     result.tokens_in, result.tokens_out, micro, bucks_charged)

        m = _NEED_INFO.fullmatch(result.text.strip()) if result.text else None
        new_cmds = attach_cmds or (m and m.group(1).lower() == "need_commands"
                                   and self._commands.available)
        new_energy = attach_energy or (m and m.group(1).lower() == "need_energy")
        if (new_cmds, new_energy) != (attach_cmds, attach_energy):
            system = self._system_prompt(character, with_commands=new_cmds,
                                         with_energy=new_energy)
            try:
                result = await self.provider.chat(
                    model=model, system=system,
                    user_content=user_content, max_tokens=MAX_OUT_TOKENS)
            except Exception as e:
                log.error("AI command-list retry failed: %s", e)
                if bucks_charged:
                    await self._refund_bucks(user, bucks_charged)
                return None, None, (
                    "😵 The AI didn't answer — try again in a minute."
                    + (f" Your {bucks_charged} 💰 was refunded." if bucks_charged else ""))
            micro = cost_micro(model, result.tokens_in, result.tokens_out)
            self._record(guild.id, user_id, model,
                         result.tokens_in, result.tokens_out, micro, 0)

        if result.refusal:
            return None, None, "🙅 That's not something I'll answer. Try something else."

        text = result.text or "…I've got nothing. Try rephrasing?"
        if _NEED_INFO.fullmatch(text.strip()):
            # a sentinel survived both passes (or the reference vanished
            # mid-flight) — a member must never see it
            text = ("Check `/help` for commands — and the footer under my "
                    "answers shows energy. I couldn't pull up the details just now.")

        # Prompt rules are a request; this is the check. Every /command in the
        # answer is resolved against the real command set, so a hallucinated
        # name is caught mechanically rather than trusted. Logged, not yet
        # rewritten or retried — one week of real traffic tells us the actual
        # rate before we decide what to do about it. Never let this break a
        # reply: the accounting above already ran.
        try:
            bogus = self._commands.unknown(text)
            if bogus:
                log.warning("AI cited command(s) that do not exist: %s — asked: %r",
                            sorted(bogus), (question or "")[:200])
        except Exception:
            log.exception("command-citation check failed")

        left_after = remaining_energy(self._user_spent_today(user_id))
        footer = (f"paid {bucks_charged} 💰" if bucks_charged
                  else f"⚡ {max(left_after, 0)}/{DAILY_FREE_ENERGY} energy left today")
        mode = tier + (f" · {character}" if character != "peepo" else "")
        return text, f"-# {mode} · {footer}", None

    async def _send_reply(self, first_send, channel, body, footer):
        """Plain-text send: first chunk via first_send (followup / reply),
        overflow via channel.send, footer subtext on the last chunk.
        Mentions are always disarmed — echoed questions and model output
        must never ping anyone."""
        chunks = split_chunks(body)
        if len(chunks[-1]) + len(footer) + 1 <= 1998:
            chunks[-1] += "\n" + footer
        else:
            chunks.append(footer)
        none = discord.AllowedMentions.none()
        sent = await first_send(chunks[0], allowed_mentions=none)
        if sent is not None:
            self._ai_msgs.append(sent.id)
        for extra in chunks[1:]:
            m = await channel.send(extra, allowed_mentions=none)
            self._ai_msgs.append(m.id)

