    def _conn(self):
        c = sqlite3.connect(DB_PATH, timeout=30)
        c.row_factory = sqlite3.Row
        return c

    async def cog_load(self):
        self.provider = build_provider()  # None (with a log line) if unconfigured
        # Paid servers answer on their own key so their spend and the home
        # community's sit behind separate OpenRouter limits. Missing second
        # key = everything on the home key, loudly, rather than paid AI dying.
        self.provider_paid = build_provider("AI_API_KEY_PAID")
        if self.provider_paid is None and self.provider is not None:
            log.warning("AI_API_KEY_PAID unset — paid servers will answer on the HOME key")
            self.provider_paid = self.provider
        if self._commands.available:
            log.info("AI command index: %d commands from %s",
                     self._commands.count, COMMAND_DOCS_PATH)
        else:
            log.warning("AI command index MISSING at %s — the AI will refuse to "
                        "name commands. Regenerate with tools/gen_command_docs.py "
                        "--json", COMMAND_DOCS_PATH)
        self._export_energy_docs()
        if TORVEX_BOT_KEY:
            self._credit_poll.start()
        else:
            log.warning("TORVEX_BOT_KEY unset — paid AI credit packs will NOT auto-apply")

    async def cog_unload(self):
        self._credit_poll.cancel()

    # ── paid-pack fulfilment ──────────────────────────────────────────────────

    def _ai_enabled(self, guild_id) -> bool:
        """Always-on guilds, plus any guild that has ever been granted credit
        (balance gating happens in _precheck, with a top-up pointer)."""
        if int(guild_id) in AI_GUILD_IDS:
            return True
        with self._conn() as c:
            return c.execute("SELECT 1 FROM ai_credit WHERE guild_id=? LIMIT 1",
                             (str(guild_id),)).fetchone() is not None

    def _enabled_guild_ids(self) -> set:
        with self._conn() as c:
            paid = {int(r[0]) for r in c.execute(
                "SELECT DISTINCT guild_id FROM ai_credit").fetchall() if r[0]}
        return set(AI_GUILD_IDS) | paid

    @tasks.loop(seconds=CREDIT_POLL_S)
    async def _credit_poll(self):
        """Apply paid AI credit packs from torvex.app. Each order is inserted
        once (UNIQUE order_ref) and acked back so the customer's Billing tab
        flips to 'applied'. Failures are logged and retried next tick."""
        headers = {"X-Bot-Key": TORVEX_BOT_KEY}
        try:
            async with aiohttp.ClientSession(timeout=aiohttp.ClientTimeout(total=15)) as sess:
                async with sess.get(f"{TORVEX_API_URL}/api/bot/ai-credit/pending",
                                    headers=headers) as r:
                    if r.status != 200:
                        log.warning("AI credit poll: HTTP %s", r.status)
                        return
                    orders = await r.json()
        except Exception as e:  # network blip — next tick
            log.debug("AI credit poll failed: %s", e)
            return
        for o in orders or []:
            try:
                gid = str(int(o["guildId"]))
                micro = int(round(float(o["creditUsd"]) * 1_000_000))
                ref = str(o["orderId"])
            except (KeyError, TypeError, ValueError):
                log.warning("AI credit poll: malformed order %r", o)
                continue
            if micro <= 0:
                continue
            note = f"torvex.app order {o.get('invoiceNumber') or ref}"
            with self._conn() as c:
                cur = c.execute(
                    "INSERT OR IGNORE INTO ai_credit(ts, guild_id, micro, note, order_ref) "
                    "VALUES (?,?,?,?,?)", (int(time.time()), gid, micro, note, ref))
                applied = cur.rowcount == 1
            try:
                async with aiohttp.ClientSession(timeout=aiohttp.ClientTimeout(total=15)) as sess:
                    async with sess.post(f"{TORVEX_API_URL}/api/bot/ai-credit/{ref}/fulfilled",
                                         headers=headers) as r2:
                        if r2.status != 200:
                            log.warning("AI credit ack for %s: HTTP %s", ref, r2.status)
            except Exception as e:
                log.warning("AI credit ack for %s failed: %s", ref, e)
            if applied:
                g = self.bot.get_guild(int(gid))
                log.info("AI credit: +$%.2f → %s (%s) via %s — balance $%.2f",
                         micro / 1e6, g.name if g else "?", gid, note,
                         self._credit_balance(gid) / 1e6)
                self._export_energy_docs()

    @_credit_poll.before_loop
    async def _before_credit_poll(self):
        await self.bot.wait_until_ready()

